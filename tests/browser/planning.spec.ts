import { test, expect } from '@playwright/test'
import { button, confirmAction, downloadJSON, nav, openPlanner, saved } from './interaction-helpers'
import type { State } from '../../src/domain/model'

test('packing resets, regeneration scopes and warning actions retain unaffected records', async ({ page }) => {
  await openPlanner(page)
  await nav(page, 'Today')
  await button(page, /^Weekly plan/).click()
  await button(page, 'Generate week').click()
  await button(page, 'Generate plan').click()
  await expect(page.locator('.prep').getByText('Roll')).toBeVisible()
  await nav(page, 'Today')
  const choices = page.getByRole('article')
  const first = choices.nth(0).getByRole('checkbox').first()
  const second = choices.nth(1).getByRole('checkbox').first()
  await first.check()
  await second.check()
  await first.uncheck()
  await first.check()
  await button(page, /Reset day.*packing/).click()
  await button(page, 'Cancel').click()
  await expect(first).toBeChecked()
  await button(page, /Reset day.*packing/).click()
  await button(page, 'Reset packing').click()
  await expect(first).not.toBeChecked()
  await expect(second).not.toBeChecked()
  await first.check()
  await second.check()
  await button(page, 'View weekly plan').click()
  await page.getByLabel('Show children').selectOption('child-1')
  await expect(choices).toHaveCount(1)
  for (const day of ['Tue', 'Wed', 'Thu', 'Fri', 'Mon']) await button(page, new RegExp('^' + day)).click()
  await button(page, /Regenerate child.*day/).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog).toContainText('Child 1 · Monday')
  await expect(dialog).toContainText('1 checked packing item')
  await button(dialog, 'Regenerate').click()
  await nav(page, 'Today')
  await expect(first).not.toBeChecked()
  await expect(second).toBeChecked()
  await nav(page, 'Week')
  await page.getByLabel('Show children').selectOption('child-1')
  await button(page, /Regenerate child.*week/).click()
  await expect(dialog).toContainText('Child 1')
  await expect(dialog).not.toContainText('checked packing')
  await button(dialog, 'Regenerate').click()
  await page.getByLabel('Show children').selectOption('')
  await button(page, 'Regenerate day for all').click()
  await expect(dialog).toContainText('All children · Monday')
  await expect(dialog).toContainText('1 checked packing item')
  await button(dialog, 'Regenerate').click()
  await button(page, 'Regenerate week').click()
  await expect(dialog).not.toContainText('checked packing')
  await button(dialog, 'Regenerate').click()
  await nav(page, 'Today')
  await button(page, /^Weekly inventory/).click()
  await button(page, 'Roll availability').click()
  await page.locator('summary').click()
  await expect(page.getByText('Roll is unavailable.').first()).toBeVisible()
  await button(page, 'Regenerate affected day').first().click()
  await expect(dialog).toContainText('All children · Monday')
  await button(dialog, 'Regenerate').click()
  await nav(page, 'Foods')
  await confirmAction(page, button(page, 'Delete Roll'), true)
  await saved(page)
  await page.reload()
  await button(page, 'Saved on this device').click()
  const backup = await downloadJSON(page, button(page.getByRole('main'), 'Export full backup'))
  const state: State = backup.data.appState
  expect(state.foods.some(f => f.id === 'roll')).toBe(false)
  expect(state.preferences.some(p => p.foodId === 'roll')).toBe(false)
  expect(state.weeklyInventories[0].entries.some(e => e.foodId === 'roll')).toBe(false)
  const slots = state.weeklyPlans[0].days.flatMap(day => day.children.flatMap(child => child.meals.flatMap(meal => meal.slots)))
  expect(slots.some(slot => slot.foodNameSnapshot === 'Roll')).toBe(true)
  expect(state.weeklyPlans[0].packedSlots).toEqual([])
})
