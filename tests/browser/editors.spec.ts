import { test, expect } from '@playwright/test'
import { button, confirmAction, downloadJSON, nav, openPlanner, saved } from './interaction-helpers'

test('saving one child preserves other drafts and adding a child creates an empty schedule', async ({ page }) => {
  await page.goto('./#setup')
  const fields = page.getByLabel('Child name', { exact: true })
  await fields.nth(1).fill('Second draft')
  await fields.first().fill('First draft')
  await button(page, 'Save name').first().click()
  await expect(fields.nth(1)).toHaveValue('Second draft')
  await button(page, 'Save name').nth(1).click()
  await page.getByLabel('Add another child').fill('Example child')
  await button(page, 'Add child').click()
  await saved(page)
  await page.reload()
  await expect(fields.first()).toHaveValue('First draft')
  await expect(fields.nth(1)).toHaveValue('Second draft')
  await expect(fields.nth(2)).toHaveValue('Example child')
  await button(page, 'Schedules').click()
  await page.getByRole('combobox', { name: 'Child', exact: true }).selectOption({ label: 'Example child' })
  await expect(page.getByText('No meals scheduled for this weekday.')).toBeVisible()
})

test('keyboard skip keeps the selected screen and desktop navigation respects browser history', async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 900 })
  await page.goto('./#foods')
  const skip = page.getByRole('link', { name: 'Skip to content' })
  await page.keyboard.press('Tab')
  await expect(skip).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page).toHaveURL(/#foods$/)
  await expect(page.getByRole('main')).toBeFocused()
  const desktop = page.getByRole('navigation', { name: 'Main navigation' })
  const backup = await downloadJSON(page, button(page.getByRole('complementary'), 'Export full backup'))
  expect(backup.data.appState.children).toHaveLength(2)
  await button(desktop, 'Weekly plan').click()
  await button(page, 'Review inventory').click()
  await page.goBack()
  await expect(page.getByRole('heading', { name: 'Weekly plan' })).toBeVisible()
  await page.goForward()
  await expect(page.getByRole('heading', { name: 'Inventory' })).toBeVisible()
  await page.locator('a.brand').click()
  await button(page, 'Set up planner').click()
  await button(page, 'Continue').click()
  await button(page, 'Back').click()
  await expect(page.getByLabel('Child name', { exact: true }).first()).toBeVisible()
  await button(page, 'Close guide').click()
  await expect(button(page, 'Continue')).toHaveCount(0)
  await button(page, 'Install & backup info').click()
  await expect(page.getByRole('heading', { name: 'Data & backups' })).toBeVisible()
})

