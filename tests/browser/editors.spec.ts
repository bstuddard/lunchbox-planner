test('category and food editors validate, filter, archive, restore and delete', async ({ page }) => {
  await openPlanner(page)
  await nav(page, 'Foods')
  const click = (name: string) => button(page, name).click()
  await click('Categories')
  await page.getByLabel('Category name').fill('Bread')
  await page.getByLabel('Variety role').selectOption('main')
  await click('Add category')
  await click('Edit Bread')
  await expect(page.getByLabel('Variety role')).toHaveValue('main')
  await click('Cancel edit')
  await click('Edit Bread')
  await page.getByLabel('Category name').fill('Grain')
  await click('Save category')
  await click('Close dialog')
  await click('Add food')
  await page.getByLabel('Food name').fill('Test roll')
  await click('Save food')
  await expect(page.getByText(/select at least one category/)).toBeVisible()
  await page.getByLabel('Grain', { exact: true }).check()
  await page.getByLabel('Main', { exact: true }).check()
  await page.getByLabel('Notes (optional)').fill('Slice before packing')
  await click('Save food')
  await page.getByLabel('Filter by category').selectOption({ label: 'Grain' })
  await page.getByLabel('Search foods').fill('missing')
  await expect(button(page, 'Edit Test roll')).toHaveCount(0)
  await page.getByLabel('Search foods').fill('roll')
  await click('Edit Test roll')
  await expect(page.getByLabel('Notes (optional)')).toHaveValue('Slice before packing')
  await page.getByLabel('Food name').fill('Cancelled edit')
  await click('Cancel')
  await click('Categories')
  await click('Delete Grain')
  await expect(button(page, 'Edit Grain')).toBeVisible()
  await page.keyboard.press('Escape')
  await confirmAction(page, button(page, 'Archive Test roll'), false)
  await confirmAction(page, button(page, 'Archive Test roll'), true)
  await expect(button(page, 'Edit Test roll')).toHaveCount(0)
  await page.getByLabel('Filter foods').selectOption('archived')
  await click('Unarchive Test roll')
  await page.getByLabel('Filter foods').selectOption('')
  await confirmAction(page, button(page, 'Delete Test roll'), false)
  await confirmAction(page, button(page, 'Delete Test roll'), true)
  await click('Categories')
  await confirmAction(page, button(page, 'Delete Grain'), false)
  await confirmAction(page, button(page, 'Delete Grain'), true)
  await expect(button(page, 'Edit Grain')).toHaveCount(0)
  await click('Close dialog')
  await expect(button(page, 'Edit Roll')).toBeVisible()
  await saved(page)
  await page.reload()
  await expect(button(page, 'Edit Test roll')).toHaveCount(0)
  await click('Categories')
  await expect(button(page, 'Edit Grain')).toHaveCount(0)
})

test('inventory copy and bulk clearing affect only the selected week', async ({ page }) => {
  await openPlanner(page)
  await nav(page, 'Inventory')
  const stock = button(page, 'Roll availability')
  await button(page, 'Copy last week').click()
  await expect(page.getByText('No saved inventory for the previous week.')).toBeVisible()
  await button(page, 'Next week').click()
  await expect(stock).toHaveAttribute('aria-pressed', 'false')
  await confirmAction(page, button(page, 'Copy last week'), false)
  await expect(stock).toHaveAttribute('aria-pressed', 'false')
  await confirmAction(page, button(page, 'Copy last week'), true)
  await expect(stock).toHaveAttribute('aria-pressed', 'true')
  await page.getByLabel('Filter foods').selectOption('yes')
  await stock.click()
  await expect(stock).toHaveCount(0)
  await page.getByLabel('Filter foods').selectOption('no')
  await expect(stock).toBeVisible()
  await page.getByLabel('Filter foods').selectOption('')
  await confirmAction(page, button(page, 'All unavailable'), false)
  await expect(button(page, 'Beans availability')).toHaveAttribute('aria-pressed', 'true')
  await confirmAction(page, button(page, 'All unavailable'), true)
  await expect(button(page, 'Beans availability')).toHaveAttribute('aria-pressed', 'false')
  await button(page, 'Previous week').click()
  await expect(stock).toHaveAttribute('aria-pressed', 'true')
  await saved(page)
  await page.reload()
  await button(page, 'Next week').click()
  await expect(stock).toHaveAttribute('aria-pressed', 'false')
})

test('preferences support all ratings, filters and independent child selections', async ({ page }) => {
  await openPlanner(page)
  await button(page, 'Preferences').click()
  await page.getByLabel('Search preferences').fill('App')
  await page.getByLabel('Preference category').selectOption('cat-fruit')
  await expect(button(page, 'Roll liked')).toHaveCount(0)
  for (const rating of ['liked', 'neutral', 'disliked']) {
    await button(page, 'Apple ' + rating).click()
    await expect(button(page, 'Apple ' + rating)).toHaveAttribute('aria-pressed', 'true')
  }
  await page.getByLabel('Disliked only').check()
  await expect(button(page, 'Apple disliked')).toBeVisible()
  await page.getByRole('combobox', { name: 'Child', exact: true }).selectOption('child-2')
  await expect(button(page, 'Apple disliked')).toHaveCount(0)
  await page.getByLabel('Disliked only').uncheck()
  await expect(button(page, 'Apple neutral')).toHaveAttribute('aria-pressed', 'true')
  await saved(page)
  await page.reload()
  await button(page, 'Preferences').click()
  await expect(button(page, 'Apple disliked')).toHaveAttribute('aria-pressed', 'true')
})

test('schedule editing, meal order and selective weekday copies survive reload', async ({ page }) => {
  await page.goto('./#setup')
  const click = (name: string) => button(page, name).click()
  await click('Schedules')
  await click('Add meal')
  await page.getByLabel('Meal name').fill('Afternoon snack')
  await click('Remove requirement')
  await click('Save meal')
  await expect(page.getByText(/at least one category/)).toBeVisible()
  await click('Add requirement')
  await page.getByLabel('Required category').selectOption('cat-fruit')
  await page.getByLabel('Quantity').fill('3')
  await click('Save meal')
  await expect(page.getByText('3 × Fruit')).toBeVisible()
  await click('Edit Afternoon snack')
  await page.getByLabel('Meal name').fill('Draft')
  await click('Cancel')
  await click('Move Afternoon snack earlier')
  await expect(page.locator('.list-row strong')).toHaveText(['Morning snack', 'Afternoon snack', 'Lunch'])
  await click('Move Afternoon snack later')
  await expect(button(page, 'Move Afternoon snack later')).toBeDisabled()
  await click('Copy Monday to weekdays')
  await click('Cancel')
  await click('Copy Monday to weekdays')
  for (const day of ['Wednesday', 'Thursday', 'Friday']) await page.getByLabel(day).uncheck()
  await click('Replace selected days')
  await click('Wed')
  await expect(button(page, 'Edit Afternoon snack')).toHaveCount(0)
  await click('Tue')
  await expect(button(page, 'Edit Afternoon snack')).toBeVisible()
  await confirmAction(page, button(page, 'Remove Afternoon snack'), false)
  await confirmAction(page, button(page, 'Remove Afternoon snack'), true)
  await expect(button(page, 'Edit Afternoon snack')).toHaveCount(0)
  await saved(page)
  await page.reload()
  await click('Schedules')
  await expect(button(page, 'Edit Afternoon snack')).toBeVisible()
  await page.getByRole('combobox', { name: 'Child', exact: true }).selectOption('child-2')
  await expect(button(page, 'Edit Afternoon snack')).toHaveCount(0)
})
